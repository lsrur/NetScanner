import Foundation

/// Parses bundled `key<TAB>value` files.
private func loadTable<Key: Hashable>(_ resource: String, key: (Substring) -> Key?) -> [Key: String] {
    guard let url = Bundle.main.url(forResource: resource, withExtension: "tsv"),
          let text = try? String(contentsOf: url, encoding: .utf8) else { return [:] }
    var table: [Key: String] = [:]
    for line in text.split(separator: "\n") {
        guard let tab = line.firstIndex(of: "\t"), let parsed = key(line[..<tab]) else { continue }
        table[parsed] = String(line[line.index(after: tab)...])
    }
    return table
}

/// IEEE MA-L registry, generated by `scripts/update-oui.sh`.
enum OUIDatabase {
    private static let vendors = loadTable("oui") { UInt32($0, radix: 16) }

    static func vendor(for mac: MACAddress) -> String? {
        if mac.isLocallyAdministered { return "Private (randomized)" }
        return vendors[mac.ouiPrefix]
    }
}

/// TCP service names from /etc/services, generated by `scripts/update-services.sh`.
enum ServiceNames {
    private static let names = loadTable("services") { UInt16($0) }

    static func name(for port: UInt16) -> String? {
        names[port]
    }
}
